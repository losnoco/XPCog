void xpcog_register_libvgm(xpcog::PluginRegistry& r) {
    r.addDecoder({
        .name       = "LibVgmDecoder",
        .priority   = xpcog::kLibVgmPriority,
        .extensions = xpcog::kExtensions,
        .mimeTypes  = {},
        .create     = []() -> xpcog::DecoderPtr {
            return std::make_unique<xpcog::LibVgmDecoder>();
        },
        .available = nullptr,
    });
}
