// VGM, S98, DRO and GYM -- chip register logs, replayed on emulated hardware.
//
// Port of Cog Plugins/libvgmPlayer, on ValleyBell's libvgm (ports/libvgm).
// These four formats are not music files in the ordinary sense and not tracker
// modules either: each is a timestamped log of everything that was written to a
// sound chip's registers, so playing one means emulating the chip and feeding it
// the writes at the right moments. libvgm carries around fifty such emulators --
// the YM2612 in a Mega Drive, the SN76489 in a Master System, the OPL family,
// the SCC, the C140, the Namco WSG -- which is why one library covers a shelf of
// consoles.
//
// **The priority is 1.25, and this is one of the few places in the tree that
// needs a number at all.** Every extension here is claimed by something else
// already: `.vgm` and `.vgz` by both Game_Music_Emu and vgmstream, `.gym` by
// Game_Music_Emu, `.dro` by AdPlug and vgmstream. Unlike `.ahx` or `.mus`,
// content does not settle it -- all of them genuinely read these files, they
// just read fewer chips or read them less accurately. So something has to say
// which is preferred, and 1.25 is Cog's number for the same reason.
//
// Worth knowing what the number is and is not doing. At the *default* priority
// this decoder would still win today, because ties break by registration order
// and codecs/CMakeLists.txt happens to enter this directory before gme's. That
// is an ordering accident rather than a decision, which is exactly why the
// number is here: dropped below the catch-alls, a Mega CD VGM opens as
// Game_Music_Emu's "Sega MegaCD / SegaCD" instead, with a different length and
// a different emulator behind it. Checked by doing it.
//
// Cog gets the same effect a different way: its container appends `#0` to every
// URL, with the comment "these are included so they can override AdPlug and
// VGMStream". That is a fragment carrying no information, on a format with no
// subsongs, doing a priority's job. Here the priority does it and there is no
// container at all.
//
// Three other differences from Cog:
//
//   * **The length includes the loops, the fade and the trailing silence.** Cog
//     reports `Tick2Second(GetTotalTicks())`, which is one pass through the file
//     and nothing else -- while PlayerA goes on to play `loopCount` passes, fade
//     over the configured seconds, and add half a second of silence. On a
//     looping VGM, which is most of them, Cog's playlist shows roughly half the
//     time the track actually takes. `GetTotalTime()` with the loop, fade and
//     silence flags is the number PlayerA is actually working to.
//
//   * **The end of the track comes from the player's own state** rather than
//     from an event callback with a flag behind it. PlayerA raises
//     PLAYSTATE_FIN when the fade and the trailing silence are both done
//     (playera.cpp, `_myPlayState |= PLAYSTATE_FIN`), which is the same moment
//     PLREVT_END fires and needs no plumbing to observe. It matters that this is
//     asked rather than inferred: PlayerA::Render fills the buffer with silence
//     and reports success when the player has stopped, so a short read never
//     signals the end.
//
//   * **The OPL4 sample ROM is optional.** See requestFile() below.

