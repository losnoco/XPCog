//========= The shared tables ========//

const Tables& Tables::shared() {
    /// 100 waveforms of 256 samples. Fixed by the format, not by the file.
    constexpr std::size_t kWaveBankSize = 100 * 256;

    static const Tables tables = [] {
        Tables built;

        // The waveform bank is 100 * 256 signed bytes and nothing else. Widened
        // to int16 here because the mixer indexes melodic and percussive
        // waveforms through the same pointer, and percussion does not fit in a
        // byte.
        //
        // Sized to the full bank whatever the file holds, so that a wave index
        // of 99 -- which the file is free to name -- reads zeros from a short
        // table rather than off the end of it.
        built.waveTable.assign(kWaveBankSize, 0);
        for (unsigned i = 0; i < kOrganyaWaveTableSize && i < kWaveBankSize; ++i) {
            built.waveTable[i] =
                static_cast<std::int16_t>(static_cast<signed char>(kOrganyaWaveTable[i]));
        }

        const Waveforms shapes;

        // Which .pxt file each of the twelve percussion slots plays. Six slots
        // name no file at all and stay silent; that is the format, not an
        // omission -- Cave Story's percussion uses six drums and Organya
        // reserved a dozen slots for them.
        static const unsigned patch[12] = {0x96, 0, 0x97, 0, 0x9a, 0x98,
                                           0x99, 0, 0x9b, 0, 0,    0};

        for (unsigned drum = 0; drum < 12; ++drum) {
            if (patch[drum] == 0) {
                continue;
            }
            unsigned file = kOrganyaPxtCount;
            for (unsigned candidate = 0; candidate < kOrganyaPxtCount; ++candidate) {
                if (kOrganyaPxtId[candidate] == patch[drum]) {
                    file = candidate;
                    break;
                }
            }
            if (file == kOrganyaPxtCount) {
                continue;  // No such parameter file: a silent slot.
            }

            Pxt parameters;
            parameters.load(
                std::string_view{reinterpret_cast<const char*>(kOrganyaPxtData[file]),
                                 kOrganyaPxtSize[file]},
                shapes);

            // Synthesise and mix the drum's four component channels. They are
            // not all the same length, so the sample grows to the longest.
            std::vector<std::int16_t>& sample = built.drums[drum];
            for (const PxtChannel& channel : parameters.channels) {
                const std::vector<int> rendered = channel.synth();
                if (rendered.size() > sample.size()) {
                    sample.resize(rendered.size());
                }
                for (std::size_t at = 0; at < rendered.size(); ++at) {
                    sample[at] = static_cast<std::int16_t>(sample[at] + rendered[at]);
                }
            }
        }
        return built;
    }();
    return tables;
}

//========= PART 2 : SONG PLAYER (ORG) ========//

bool Song::load(std::span<const std::byte> data, double sampleRate) {
    tables_ = &Tables::shared();

    Reader in{data};
    if (!in.match("Org-02")) {
        return false;
    }

    msPerBeat_ = in.word();
    (void)in.byte();  // steps_per_bar -- display only, the player never reads it
    (void)in.byte();  // beats_per_step -- likewise
    loopStart_ = in.dword();
    loopEnd_   = in.dword();

    // Every count below is read from the file and multiplied out into an
    // allocation, so each is bounded before it is trusted. The original read
    // straight into a vector sized by a 16-bit field, which cannot overflow but
    // can ask for 65,535 events that are not there -- and then read past the
    // end of the file for every one of them.
    std::size_t counts[kTracks]{};
    for (std::size_t track = 0; track < kTracks; ++track) {
        tracks_[track].tuning = in.word();
        tracks_[track].wave   = in.byte();
        tracks_[track].pi     = in.byte() != 0;
        counts[track]         = static_cast<std::size_t>(in.word());
    }
    if (in.exhausted()) {
        return false;
    }

    // Five parallel arrays per track: beat numbers first, then notes, lengths,
    // volumes and pannings, each complete before the next begins.
    for (std::size_t track = 0; track < kTracks; ++track) {
        std::vector<std::pair<int, Event>> events(counts[track]);
        for (auto& event : events) {
            event.first = in.dword();
        }
        for (auto& event : events) {
            event.second.note = in.byte();
        }
        for (auto& event : events) {
            event.second.length = in.byte();
        }
        for (auto& event : events) {
            event.second.volume = in.byte();
        }
        for (auto& event : events) {
            event.second.panning = in.byte();
        }
        if (in.exhausted()) {
            return false;
        }
        tracks_[track].events.insert(events.begin(), events.end());
    }

    sampleRate_ = sampleRate;
    // Truncated, not rounded, and the decoder's length calculation has to agree
    // with this or the track ends somewhere the audio does not. See the note in
    // OrganyaDecoder.cpp.
    samplesPerBeat_ =
        static_cast<std::size_t>(static_cast<double>(msPerBeat_) * sampleRate * 1e-3);
    if (msPerBeat_ <= 0 || samplesPerBeat_ == 0) {
        return false;
    }

    reset();
    return true;
}

void Song::reset() {
    beat_ = 0;
    for (Instrument& track : tracks_) {
        track.phaseacc    = 0.0;
        track.phaseinc    = 0.0;
        track.curVolume   = 0.0;
        track.curPan      = 0;
        track.curLength   = 0;
        track.curWaveSize = 0;
        track.curWave     = nullptr;
    }
}

void Song::startNote(Instrument& track, std::size_t index) {
    const auto found = track.events.find(beat_);
    if (found == track.events.end()) {
        return;
    }
    const Event& event = found->second;

    // 255 in any field means "carry on with what was already set".
    if (event.volume != 255) {
        // 4e-6 is the player's master volume and is the reason Organya comes
        // out at a listenable level at all: the waveforms are signed bytes and
        // sixteen tracks are summed without any headroom, so the scale factor
        // is doing the work a mixer would otherwise do. Loud songs can and do
        // exceed unity; see the note on clipping in OrganyaDecoder.cpp.
        constexpr double kMasterVolume = 4e-6;
        track.curVolume                = event.volume * kMasterVolume;
    }
    if (event.panning != 255) {
        track.curPan = event.panning;
    }
    if (event.note == 255) {
        return;
    }

    // Equal temperament, with the instrument's own tuning in thousandths of a
    // semitone. 155.376 puts note 44 at 440 Hz:
    //   12*log(256*440)/log(2) - (4*12-3-1)
    // -- 256 because the waveform being stepped through is 256 samples long, so
    // the frequency here is a sample rate rather than a pitch.
    const double freq =
        std::pow(2.0, (event.note + (track.tuning / 1000.0) + 155.376) / 12);

    track.phaseinc = freq / sampleRate_;
    track.phaseacc = 0.0;

    if (index < kFirstDrumTrack) {
        track.curWave     = &tables_->waveTable[256 * (track.wave % 100)];
        track.curWaveSize = 256;
        // In "pi" mode the note lasts exactly 1024 waveform samples whatever
        // length the event carries -- a fixed number of cycles rather than a
        // fixed duration, so it is shorter the higher the note.
        track.curLength =
            track.pi ? static_cast<std::int64_t>(1024 / track.phaseinc)
                     : static_cast<std::int64_t>(event.length) *
                           static_cast<std::int64_t>(samplesPerBeat_);
    } else {
        const std::vector<std::int16_t>& drum = tables_->drums[track.wave % 12];
        // Percussion is pitched linearly rather than by temperament: the note
        // number scales the playback rate of a 22,050 Hz sample directly.
        track.phaseinc    = event.note * (22050 / 32.5) / sampleRate_;
        track.curWave     = drum.data();
        track.curWaveSize = static_cast<std::int64_t>(drum.size());
        // Note 0 on a percussion track gives a rate of zero, which the original
        // divided by. It reaches this codec from any file that asks for it, so
        // it is a silent note rather than an infinity cast to an int.
        track.curLength =
            track.phaseinc > 0.0
                ? static_cast<std::int64_t>(static_cast<double>(drum.size()) / track.phaseinc)
                : 0;
    }

    // The six unfilled percussion slots land here.
    if (track.curWaveSize <= 0) {
        track.curLength = 0;
    }
}

void Song::renderBeat(float* out) {
    if (loopEnd_ > loopStart_ && beat_ == loopEnd_) {
        beat_ = loopStart_;
    }

    const auto frames = static_cast<std::int64_t>(samplesPerBeat_);
    if (out != nullptr) {
        std::fill_n(out, samplesPerBeat_ * 2, 0.0F);
    }

    for (std::size_t index = 0; index < kTracks; ++index) {
        Instrument& track = tracks_[index];
        startNote(track, index);

        const std::int64_t n = std::min(frames, track.curLength);
        if (n <= 0) {
            continue;
        }

        if (out != nullptr) {
            // Panning is a 0..12 dial with 6 in the middle, and each side is
            // clamped there -- so centre is full volume on both, not half.
            const double left  = (track.curPan > 6 ? 12 - track.curPan : 6) * track.curVolume;
            const double right = (track.curPan < 6 ? track.curPan : 6) * track.curVolume;

            for (std::int64_t p = 0; p < n; ++p) {
                const double pos = track.phaseacc + (static_cast<double>(p) * track.phaseinc);

                // A plain `curWave[unsigned(pos) % curWaveSize]` would do, and
                // is what the format's own player on the DS does. Lanczos-2 is
                // Bisqwit's addition and is audibly better on the low rumbles
                // that Organya's bass waveforms are mostly made of, so it is
                // part of what this format sounds like now.
                constexpr int radius  = 2;
                const auto    lanczos = [](double d) -> double {
                    if (d == 0.) {
                        return 1.;
                    }
                    if (std::fabs(d) > radius) {
                        return 0.;
                    }
                    const double dr = (d *= 3.14159265) / radius;
                    return std::sin(d) * std::sin(dr) / (d * dr);
                };

                // Widening the window when the waveform is being read slower
                // than one sample per output sample; narrowing it would alias.
                const double scale = 1 / track.phaseinc > 1 ? 1 : 1 / track.phaseinc;
                double       density = 0, sample = 0;
                // int64 rather than int: pos accumulates across a note that can
                // run for minutes at a phase increment of tens, which overflows
                // a 32-bit window index long before the note ends.
                const auto low  = static_cast<std::int64_t>((-radius / scale) + pos - 0.5);
                const auto high = static_cast<std::int64_t>((radius / scale) + pos + 0.5);
                for (std::int64_t m = low; m < high; ++m) {
                    const double factor = lanczos((static_cast<double>(m) - pos + 0.5) * scale);
                    density += factor;
                    sample += track.curWave[m < 0 ? 0 : m % track.curWaveSize] * factor;
                }
                if (density > 0.) {
                    sample /= density;
                }

                out[(p * 2) + 0] += static_cast<float>(sample * left);
                out[(p * 2) + 1] += static_cast<float>(sample * right);
            }
        }

        // Exactly what the loop above would have left behind, and the only
        // state it touches. See renderBeat()'s note in the header.
        //
        // The loop reads `phaseacc + p * phaseinc` rather than adding to
        // phaseacc each sample, which is what makes this line able to say
        // "exactly". The original accumulated, and a note held for a minute
        // accumulates a minute's worth of rounding into its own phase; this
        // form has none of that, and costs a multiply.
        track.phaseacc += track.phaseinc * static_cast<double>(n);
        track.curLength -= n;
    }

    ++beat_;
}

