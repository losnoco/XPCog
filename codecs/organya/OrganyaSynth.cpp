//========= Reading the file ========//

/// A cursor over the file's bytes with the format's own integer widths.
///
/// Everything in an .org file is little-endian and unsigned, and a read past
/// the end answers -1 rather than throwing -- which is what the original's
/// fgetc() did, and which the loader below checks for by validating what it
/// read rather than by asking whether the read succeeded.
class Reader {
public:
    explicit Reader(std::span<const std::byte> data) : data_(data) {}

    [[nodiscard]] int byte() {
        if (at_ >= data_.size()) {
            exhausted_ = true;
            return -1;
        }
        return static_cast<int>(static_cast<unsigned char>(data_[at_++]));
    }
    [[nodiscard]] int word() {
        const int low  = byte();
        const int high = byte();
        return (high << 8) + low;
    }
    [[nodiscard]] int dword() {
        const int low  = word();
        const int high = word();
        return (high << 16) + low;
    }

    /// True once any read has run off the end. The loader asks this once, at
    /// the end, rather than after every field: a truncated file is a truncated
    /// file whichever field it stopped on.
    [[nodiscard]] bool exhausted() const { return exhausted_; }

    [[nodiscard]] bool match(std::string_view signature) {
        if (data_.size() < signature.size()) {
            return false;
        }
        const bool same = std::memcmp(data_.data(), signature.data(), signature.size()) == 0;
        at_ = signature.size();
        return same;
    }

private:
    std::span<const std::byte> data_;
    std::size_t                at_        = 0;
    bool                       exhausted_ = false;
};

//========= PART 1 : SOUND EFFECT PLAYER (PXT) ========//

/// The six waveforms every PixTone generator is built from.
///
/// Bit-exact with PixTone v1.0.3, including the pseudorandom one -- the LFSR is
/// stepped once per sample whether or not that sample is the one being written,
/// so the noise waveform depends on having run the whole loop in order.
struct Waveforms {
    signed char shape[6][256]{};

    Waveforms() {
        unsigned seed = 0;
        for (unsigned i = 0; i < 256; ++i) {
            seed = (seed * 214013) + 2531011;  // Linear congruential generator
            shape[0][i] = static_cast<signed char>(
                0x40 * std::sin(static_cast<double>(i) * 3.1416 / 0x80));  // Sine
            shape[1][i] = static_cast<signed char>(((0x40 + i) & 0x80) != 0 ? 0x80 - i
                                                                            : i);  // Triangle
            shape[2][i] = static_cast<signed char>(-0x40 + (i / 2));  // Sawtooth up
            shape[3][i] = static_cast<signed char>(0x40 - (i / 2));   // Sawtooth down
            shape[4][i] = static_cast<signed char>(0x40 - (i & 0x80));  // Square
            shape[5][i] = static_cast<signed char>(seed >> 16) / 2;     // Pseudorandom
        }
    }
};

/// Reads the numeric values out of a PixTone parameter file: one per line,
/// after a colon, blank lines ignored.
///
/// PixTone wrote these as plain text and the original player parsed them with
/// fgets and strtod, so this is deliberately as forgiving: a line with no colon
/// reads as zero, and running off the end reads as zero for ever. The six files
/// shipped here are well-formed, and a parser that rejected anything else would
/// only make it harder to drop in a replacement drum kit.
class PxtReader {
public:
    explicit PxtReader(std::string_view text) : text_(text) {}

    [[nodiscard]] double value() {
        while (at_ < text_.size()) {
            const std::size_t lineEnd = std::min(text_.find('\n', at_), text_.size());
            std::string_view  line    = text_.substr(at_, lineEnd - at_);
            at_                       = lineEnd + 1;

            if (!line.empty() && line.back() == '\r') {
                line.remove_suffix(1);
            }
            if (line.empty()) {
                continue;  // Blank line: try the next one.
            }

            const std::size_t colon = line.find(':');
            if (colon == std::string_view::npos) {
                return 0.0;
            }
            // strtod wants a terminator; the line is a view into a byte array
            // that has none, so this is the one copy in the parse.
            const std::string tail{line.substr(colon + 1)};
            return std::strtod(tail.c_str(), nullptr);
        }
        return 0.0;
    }

    [[nodiscard]] int integer() { return static_cast<int>(value()); }

private:
    std::string_view text_;
    std::size_t      at_ = 0;
};

/// One PixTone channel: three signal generators feeding an envelope.
struct PxtChannel {
    struct Wave {
        const signed char* wave   = nullptr;
        double             pitch  = 0.0;
        int                level  = 0;
        int                offset = 0;
    };

    /// Linearly interpolated between an initial value and three key points.
    struct Envelope {
        int initial = 0;
        struct Point {
            int time = 0;
            int val  = 0;
        } p[3];

        [[nodiscard]] int evaluate(int i) const {
            int prevval = initial, prevtime = 0;
            int nextval = 0, nexttime = 256;
            for (int j = 2; j >= 0; --j) {
                if (i < p[j].time) {
                    nexttime = p[j].time;
                    nextval  = p[j].val;
                }
            }
            for (int j = 0; j <= 2; ++j) {
                if (i >= p[j].time) {
                    prevtime = p[j].time;
                    prevval  = p[j].val;
                }
            }
            if (nexttime <= prevtime) {
                return prevval;
            }
            return ((i - prevtime) * (nextval - prevval) / (nexttime - prevtime)) + prevval;
        }
    };

    bool     enabled  = false;
    int      nsamples = 0;
    Wave     carrier;    // The main signal to be generated.
    Wave     frequency;  // Modulator to the main signal.
    Wave     amplitude;  // Modulator to the main signal.
    Envelope envelope;

    [[nodiscard]] std::vector<int> synth() const {
        // nsamples reaches the divisions below, so a file claiming zero or a
        // negative length is refused here rather than dividing by it. The
        // original trusted the file; these six are trustworthy and a
        // replacement need not be.
        if (!enabled || nsamples <= 0) {
            return {};
        }
        std::vector<int> result(static_cast<std::size_t>(nsamples));

        const double count     = nsamples;
        double       mainpos   = carrier.offset;
        const double maindelta = 256 * carrier.pitch / count;

        for (std::size_t i = 0; i < result.size(); ++i) {
            const auto position = [&](double pitch) {
                return 256 * pitch * static_cast<double>(i) / count;
            };
            // Take a sample from each of the three signal generators:
            const int freqval =
                frequency.wave[0xFF & static_cast<int>(frequency.offset +
                                                       position(frequency.pitch))] *
                frequency.level;
            const int ampval =
                amplitude.wave[0xFF & static_cast<int>(amplitude.offset +
                                                       position(amplitude.pitch))] *
                amplitude.level;
            const int mainval =
                carrier.wave[0xFF & static_cast<int>(mainpos)] * carrier.level;

            // Apply amplitude and envelope to the main signal level:
            result[i] = mainval * (ampval + 4096) / 4096 *
                        envelope.evaluate(static_cast<int>(position(1.0))) / 4096;
            // Apply frequency modulation to maindelta:
            mainpos += maindelta * (1 + (freqval / (freqval < 0 ? 8192. : 2048.)));
        }
        return result;
    }
};

/// The four parallel FM/AM modulators one .pxt file describes.
struct Pxt {
    PxtChannel channels[4];

    void load(std::string_view text, const Waveforms& shapes) {
        PxtReader in{text};
        // Written out field by field rather than as a braced initialiser. The
        // original relied on brace elision *and* on left-to-right evaluation
        // inside the braces to get sixteen reads in the right order, which is
        // correct C++11 but reads like a trap.
        const auto readWave = [&] {
            PxtChannel::Wave wave;
            // The model index selects one of six shapes. Masked rather than
            // taken modulo: a negative value would index behind the array, and
            // C++'s % keeps the sign.
            wave.wave   = shapes.shape[static_cast<unsigned>(in.integer()) % 6];
            wave.pitch  = in.value();
            wave.level  = in.integer();
            wave.offset = in.integer();
            return wave;
        };

        for (PxtChannel& channel : channels) {
            channel.enabled   = in.integer() != 0;
            channel.nsamples  = in.integer();
            channel.carrier   = readWave();
            channel.frequency = readWave();
            channel.amplitude = readWave();

            channel.envelope.initial = in.integer();
            for (PxtChannel::Envelope::Point& point : channel.envelope.p) {
                point.time = in.integer();
                point.val  = in.integer();
            }
        }
    }
};

