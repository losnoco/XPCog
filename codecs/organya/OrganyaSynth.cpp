// See OrganyaSynth.hpp for what this is and where it came from.
//
// The structure follows Bisqwit's original because the format is defined by it
// as much as by any specification: the note-to-frequency constant, the master
// volume, and the Lanczos window on the wavetable lookup are all choices this
// player made and every Organya listener has since heard. Deviating from them
// would not be a better reading of the format, it would be a different player.
//
// What has changed is everything around the arithmetic: the file readers, which
// took a FILE* and now take bytes; the drum and waveform data, which came from
// a bundle and are now compiled in; and the seek path, which did not exist.

