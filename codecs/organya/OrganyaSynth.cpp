///
/// The parameter files are addressed by the number in their name -- fx96.pxt is
/// 0x96 -- rather than by position, so the patch table below reads the way the
/// format writes it and adding a drum is a matter of dropping a file in.
extern "C" {
extern const unsigned char kOrganyaWaveTable[];
extern const unsigned int  kOrganyaWaveTableSize;

extern const unsigned int         kOrganyaPxtCount;
extern const unsigned int         kOrganyaPxtId[];
extern const unsigned char* const kOrganyaPxtData[];
extern const unsigned int         kOrganyaPxtSize[];
}

